.global isr_common_stub
.extern irq_dispatch

.macro ISR_NOERRCODE num
.global isr\num
isr\num:
    pushq $0
    pushq $\num
    jmp isr_common_stub
.endm

.macro ISR_ERRCODE num
.global isr\num
isr\num:
    pushq $\num
    jmp isr_common_stub
.endm

.macro IRQ_STUB irq, num
.global irq\irq
irq\irq:
    pushq $0
    pushq $\num
    jmp isr_common_stub
.endm

